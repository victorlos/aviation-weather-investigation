
SELECT 
    FLIGHT_DATE ,
    REPORTING_AIRLINE,
    CARRIER.CARRIER_NAME,
    ORIGIN_AIRPORT_ID,
    DESTINATION_AIRPORT_ID,
    DEPARTURE_TIME,
    DEPARTURE_DELAY,
    ARRIVAL_TIME,
    ARRIVAL_DELAY,
    IS_CANCELLED,
    AIR_TIME,
    WEATHER_DELAY,
    NAS_DELAY,
    SECURITY_DELAY,
    LATE_AIRCRAFT_DELAY,
    CANCELLATION_CODE,
    CARRIER_DELAY,
    IS_DIVERTED, 
    ARRIVAL_DELAY_15
FROM {{ ref('stg_bts__flights') }} BF
LEFT JOIN {{ ref('stg_bts__carriers') }} CARRIER
ON BF.REPORTING_AIRLINE = CARRIER.CARRIER_CODE
