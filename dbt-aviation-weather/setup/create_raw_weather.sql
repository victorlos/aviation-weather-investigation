CREATE TABLE IF NOT EXISTS "AVIATION_WEATHER_PROJECT"."RAW_DATA"."RAW_WEATHER" ( ID VARCHAR , DATE NUMBER(38, 0) , ELEMENT VARCHAR , DATA_VALUE NUMBER(38, 0) , M_FLAG VARCHAR , Q_FLAG VARCHAR , S_FLAG VARCHAR , OBS_TIME NUMBER(38, 0) ); 

CREATE TEMP FILE FORMAT "AVIATION_WEATHER_PROJECT"."RAW_DATA"."temp_file_format_2026-10-18T13:40:41.691Z"
	TYPE=CSV
    SKIP_HEADER=1
    FIELD_DELIMITER=','
    TRIM_SPACE=TRUE
    FIELD_OPTIONALLY_ENCLOSED_BY='"'
    REPLACE_INVALID_CHARACTERS=TRUE
    DATE_FORMAT=AUTO
    TIME_FORMAT=AUTO
    TIMESTAMP_FORMAT=AUTO; 

COPY INTO "AVIATION_WEATHER_PROJECT"."RAW_DATA"."RAW_WEATHER" 
FROM (SELECT $1, $2, $3, $4, $5, $6, $7, $8
	FROM '@"AVIATION_WEATHER_PROJECT"."RAW_DATA"."WEATHER_DATA"') 
FILES = ('csv/by_year/2025.csv','csv/by_year/2026.csv') 
 FILE_FORMAT = '"AVIATION_WEATHER_PROJECT"."RAW_DATA"."temp_file_format_2026-10-18T13:40:41.691Z"'
