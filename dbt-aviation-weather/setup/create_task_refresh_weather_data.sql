
CREATE OR ALTER TASK "AVIATION_WEATHER_PROJECT"."DEV"."TASK_REFRESH_WEATHER_DATA"
  WAREHOUSE = "AVIATION_WEATHER_WAREHOUSE"
  SCHEDULE = 'USING CRON 0 2 * * * UTC'

AS 

    MERGE INTO "AVIATION_WEATHER_PROJECT"."RAW_DATA"."RAW_WEATHER"
    USING (
        SELECT $1, $2, $3, $4, $5, $6, $7, $8
        FROM '@"AVIATION_WEATHER_PROJECT"."RAW_DATA"."WEATHER_DATA"'
        FILES = ('csv/by_year/2025.csv','csv/by_year/2026.csv') 
        FILE_FORMAT = '"AVIATION_WEATHER_PROJECT"."RAW_DATA"."temp_file_format_2026-10-18T13:40:41.691Z"'
    

        WHERE 1=1
        AND $2::NUMBER >= TO_NUMBER(TO_CHAR(DATEADD(DAY, -30, CURRENT_DATE()), 'YYYYMMDD'))
    )
    AS source

    ON "AVIATION_WEATHER_PROJECT"."RAW_DATA"."RAW_WEATHER".ID = source.$1
    AND "AVIATION_WEATHER_PROJECT"."RAW_DATA"."RAW_WEATHER".DATE = source.$2
    AND "AVIATION_WEATHER_PROJECT"."RAW_DATA"."RAW_WEATHER".ELEMENT = source.$3
    WHEN MATCHED THEN 
        UPDATE SET
            DATA_VALUE = source.$4,
            M_FLAG = source.$5,
            Q_FLAG = source.$6,
            S_FLAG = source.$7,
            OBS_TIME = source.$8
    WHEN NOT MATCHED THEN
        INSERT (ID, DATE, ELEMENT, DATA_VALUE, M_FLAG, Q_FLAG, S_FLAG, OBS_TIME)
        VALUES (source.$1, source.$2, source.$3, source.$4, source.$5, source.$6, source.$7, source.$8);

CREATE OR REPLACE TASK AVIATION_WEATHER_PROJECT.DEV.BUILD_FACT_WEATHER
  WAREHOUSE = AVIATION_WEATHER_WAREHOUSE
  AFTER TASK_REFRESH_WEATHER_DATA

