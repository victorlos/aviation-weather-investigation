
CREATE OR REPLACE FILE FORMAT "AVIATION_WEATHER_PROJECT"."RAW_DATA"."WEATHER_REFRESH_FORMAT"
	TYPE=CSV
    SKIP_HEADER=1
    FIELD_DELIMITER=','
    TRIM_SPACE=TRUE
    FIELD_OPTIONALLY_ENCLOSED_BY='"'
    REPLACE_INVALID_CHARACTERS=TRUE
    DATE_FORMAT=AUTO
    TIME_FORMAT=AUTO
    TIMESTAMP_FORMAT=AUTO; 

CREATE OR ALTER TASK "AVIATION_WEATHER_PROJECT"."DEV"."TASK_REFRESH_WEATHER_DATA"
  WAREHOUSE = "AVIATION_WEATHER_WAREHOUSE"
  SCHEDULE = 'USING CRON 0 2 * * * UTC'

AS 

    MERGE INTO "AVIATION_WEATHER_PROJECT"."RAW_DATA"."RAW_WEATHER" AS T
    USING (
        SELECT $1::VARCHAR as ID, $2::NUMBER AS "DATE", $3::VARCHAR AS ELEMENT, $4::VARCHAR AS DATA_VALUE, $5::VARCHAR AS M_FLAG, $6::VARCHAR AS Q_FLAG, $7::VARCHAR AS S_FLAG, $8::NUMBER AS OBS_TIME
        FROM @"AVIATION_WEATHER_PROJECT"."RAW_DATA"."WEATHER_DATA"/csv/by_year/2026.csv
        (FILE_FORMAT => "AVIATION_WEATHER_PROJECT"."RAW_DATA"."WEATHER_REFRESH_FORMAT")
        WHERE  "DATE" >= TO_NUMBER(TO_CHAR(DATEADD(DAY, -30, CURRENT_DATE()), 'YYYYMMDD'))
    )
    AS source

    ON T.ID = source.ID
    AND T.DATE = source.DATE
    AND T.ELEMENT = source.ELEMENT
    WHEN MATCHED AND (
       t.DATA_VALUE IS DISTINCT FROM source.DATA_VALUE
    OR t.Q_FLAG     IS DISTINCT FROM source.Q_FLAG
    OR t.M_FLAG     IS DISTINCT FROM source.M_FLAG
    OR t.S_FLAG     IS DISTINCT FROM source.S_FLAG
    OR t.OBS_TIME   IS DISTINCT FROM source.OBS_TIME
    ) THEN  
    UPDATE SET
        T.DATA_VALUE = source.DATA_VALUE,
        T.M_FLAG = source.M_FLAG,
        T.Q_FLAG = source.Q_FLAG,
        T.S_FLAG = source.S_FLAG,
        T.OBS_TIME = source.OBS_TIME

            
    WHEN NOT MATCHED THEN
        INSERT (ID, DATE, ELEMENT, DATA_VALUE, M_FLAG, Q_FLAG, S_FLAG, OBS_TIME)
        VALUES (source.ID, source.DATE, source.ELEMENT, source.DATA_VALUE, source.M_FLAG, source.Q_FLAG, source.S_FLAG, source.OBS_TIME);


CREATE OR REPLACE TASK AVIATION_WEATHER_PROJECT.DEV.BUILD_FACT_WEATHER
  WAREHOUSE = AVIATION_WEATHER_WAREHOUSE
  AFTER TASK_REFRESH_WEATHER_DATA

AS 

EXECUTE DBT PROJECT AVIATION_WEATHER_PROJECT.CICD.AVIATION_WEATHER_DBT_OBJECT_GH_ACTION
        ARGS = 'build --select +fact_weather+';

-- Turn the tasks on: the child first, then the root
ALTER TASK AVIATION_WEATHER_PROJECT.DEV.BUILD_FACT_WEATHER RESUME;
ALTER TASK AVIATION_WEATHER_PROJECT.DEV.TASK_REFRESH_WEATHER_DATA RESUME;