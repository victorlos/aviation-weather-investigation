
  create or replace   view AVIATION_WEATHER_PROJECT.DEV.flights_w_coord
  
   as (
    SELECT 
FLIGHTDATE,
REPORTING_AIRLINE,
CARRIER.DESCRIPTION AS AIRLINE_NAME,
ORIGINAIRPORTID,
ORI_AIR.DISPLAY_AIRPORT_NAME AS ORIGIN_AIRPORT,
ORI_AIR.AIRPORT_COUNTRY_NAME AS ORIGIN_COUNTRY,
ORI_AIR.DISPLAY_CITY_MARKET_NAME_FULL AS ORIGIN_CITY_STATE,
ORI_AIR.LATITUDE AS ORIGIN_LAT,
ORI_AIR.LONGITUDE AS ORIGIN_LONG,
DESTAIRPORTID,
DEST_AIR.DISPLAY_AIRPORT_NAME AS DESTINATION_AIRPORT,
DEST_AIR.AIRPORT_COUNTRY_NAME AS DESTINATION_COUNTRY,
DEST_AIR.DISPLAY_CITY_MARKET_NAME_FULL AS DESTINATION_CITY_STATE,
DEST_AIR.LATITUDE AS DESTINATION_LAT,
DEST_AIR.LONGITUDE AS DESTINATION_LONG,
DEPTIME,
DEPDELAY,
ARRTIME,
ARRDELAY,
CANCELLED,
AIRTIME,
WEATHERDELAY,
NASDELAY,
SECURITYDELAY,
LATEAIRCRAFTDELAY
FROM AVIATION_WEATHER_PROJECT.PUBLIC.raw_flights rf
JOIN AVIATION_WEATHER_PROJECT.PUBLIC.raw_airport_coordinates ori_air
ON rf.ORIGINAIRPORTID = ori_air.AIRPORT_ID
AND ori_air.AIRPORT_IS_LATEST=1
JOIN AVIATION_WEATHER_PROJECT.PUBLIC.raw_airport_coordinates dest_air
ON rf.DESTAIRPORTID = dest_air.AIRPORT_ID 
AND dest_air.AIRPORT_IS_LATEST=1
JOIN AVIATION_WEATHER_PROJECT.PUBLIC.raw_carrier_lookup carrier
ON rf.REPORTING_AIRLINE = carrier.CODE
  );

