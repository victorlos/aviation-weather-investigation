
  
    

create or replace transient table AVIATION_WEATHER_PROJECT.DEV.dim_airports
    
    
    
    
    

    as (WITH STATIONS AS (
    SELECT 
      TRIM(SUBSTR(ALL_DATA, 1, 11))           AS STATION_ID,
      TRY_TO_DOUBLE(SUBSTR(ALL_DATA, 13, 8))  AS LATITUDE,
      TRY_TO_DOUBLE(SUBSTR(ALL_DATA, 22, 9))  AS LONGITUDE,
      TRY_TO_DOUBLE(SUBSTR(ALL_DATA, 32, 6))  AS ALTITUDE,
      TRIM(SUBSTR(ALL_DATA, 39, 2))           AS STATE,
      TRIM(SUBSTR(ALL_DATA, 42, 30))          AS NAME
    FROM AVIATION_WEATHER_PROJECT.PUBLIC.raw_stations
    WHERE 1=1
       AND TRIM(SUBSTR(ALL_DATA, 1, 3)) = 'USW' -- ONLY GET STATIONS AT US AIRPORTS
    ),
    
    AIRPORTS AS (
    SELECT 
      AIRPORT_SEQ_ID,
      AIRPORT_ID,
      AIRPORT,
      DISPLAY_AIRPORT_NAME,
      DISPLAY_AIRPORT_CITY_NAME_FULL, 
      AIRPORT_COUNTRY_NAME,
      AIRPORT_COUNTRY_CODE_ISO,
      AIRPORT_STATE_NAME, 
      AIRPORT_STATE_CODE,
      DISPLAY_CITY_MARKET_NAME_FULL,
      LATITUDE, 
      LONGITUDE
    FROM AVIATION_WEATHER_PROJECT.PUBLIC.raw_airport_coordinates
    WHERE 1=1
     AND AIRPORT_IS_LATEST = 1 -- FILTER FOR LAST ROW OF AIRPORT IN SOURCE
     AND AIRPORT_IS_CLOSED = 0 -- FILTER FOR OPEN AIRPORTS
     AND AIRPORT_COUNTRY_CODE_ISO = 'US' --FILTER FOR US AIRPORTS ONLY
    ),

    DISTANCE AS (
    SELECT
        a.AIRPORT_SEQ_ID,
        a.AIRPORT_ID,
        a.AIRPORT,
        a.DISPLAY_AIRPORT_NAME,
        a.DISPLAY_AIRPORT_CITY_NAME_FULL,
        a.AIRPORT_COUNTRY_NAME,
        a.AIRPORT_COUNTRY_CODE_ISO,
        a.AIRPORT_STATE_NAME, 
        a.AIRPORT_STATE_CODE,
        a.DISPLAY_CITY_MARKET_NAME_FULL,
        a.LATITUDE AIRPORT_LATITUDE,  
        a.LONGITUDE AIRPORT_LONGITUDE,
        
        s.STATION_ID,
        s.STATE AS STATION_STATE,
        s.NAME AS STATION_NAME,
        s.LATITUDE AS STATION_LATITUDE,
        s.LONGITUDE AS STATION_LONGITUDE,
        s.ALTITUDE AS STATION_ALTITUDE,
        HAVERSINE(a.LATITUDE, a.LONGITUDE, s.LATITUDE, s.LONGITUDE) AS DISTANCE_KM,
        ROW_NUMBER() OVER (PARTITION BY AIRPORT_ID ORDER BY HAVERSINE(a.LATITUDE, a.LONGITUDE, s.LATITUDE, s.LONGITUDE) ASC) AS ROW_NUM -- ROW_NUM TO DEDUPLICATE AIRPORTS BASED ON DISTANCE_KM
    FROM airports a
    LEFT JOIN stations s
    ON s.latitude BETWEEN a.latitude  - 0.5 AND a.latitude  + 0.5
    AND s.longitude BETWEEN a.longitude - 0.5 AND a.longitude + 0.5
    AND HAVERSINE(a.LATITUDE, a.LONGITUDE, s.LATITUDE, s.LONGITUDE) < 20 -- ONLY JOIN STATIONS WITHIN 20 KM FROM AIRPORT
    )
    
SELECT 
    AIRPORT_SEQ_ID,
    AIRPORT_ID,
    AIRPORT,
    DISPLAY_AIRPORT_NAME,
    DISPLAY_AIRPORT_CITY_NAME_FULL,
    AIRPORT_COUNTRY_NAME,
    AIRPORT_COUNTRY_CODE_ISO,
    AIRPORT_STATE_NAME, 
    AIRPORT_STATE_CODE,
    DISPLAY_CITY_MARKET_NAME_FULL,
    AIRPORT_LATITUDE,  
    AIRPORT_LONGITUDE,
    STATION_ID,
    STATION_STATE,
    STATION_NAME,
    STATION_LATITUDE,
    STATION_LONGITUDE,
    STATION_ALTITUDE,
    DISTANCE_KM
FROM DISTANCE
WHERE ROW_NUM = 1 -- DEDUPLICATE AIRPORTS WITH MORE THAN 1 STATION AND CHOOSE CLOSEST ONE
    )
;


  