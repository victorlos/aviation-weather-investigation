
-- CREATE WAREHOUSE
CREATE WAREHOUSE IF NOT EXISTS AVIATION_WEATHER_WAREHOUSE WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60;

-- CREATE DATABASE AND SCHEMA FOR PROJECT
CREATE DATABASE IF NOT EXISTS AVIATION_WEATHER_PROJECT;
CREATE SCHEMA IF NOT EXISTS AVIATION_WEATHER_PROJECT.RAW_DATA;

-- CREATE STAGE DATA FROM S3 OPEN REPOSITORY FOR WEATHER DATA
CREATE STAGE IF NOT EXISTS AVIATION_WEATHER_PROJECT.RAW_DATA.WEATHER_DATA 
	URL = 's3://noaa-ghcn-pds' 
	DIRECTORY = ( ENABLE = true );

-- CREATE STAGE DATA FOR FLIGHTS DATA
CREATE STAGE IF NOT EXISTS AVIATION_WEATHER_PROJECT.RAW_DATA.BTS_FLIGHTS
DIRECTORY = ( ENABLE = true );

-- CREATE SECRET TO CONNECT SNOWFLAKE WITH GITHUB
CREATE OR REPLACE SECRET git_secret
TYPE = password
USERNAME = 'victorlos'
PASSWORD = '{{ GITHUB_PAT }}'; -- YOUR GITHUB PAT GOES HERE

-- CREATE API INTEGRATION WITH GITHUB USING SECRET PREVIOUS DEFINED
CREATE OR REPLACE API INTEGRATION git_api_integration
API_PROVIDER = git_https_api
API_ALLOWED_PREFIXES = ('https://github.com')
ALLOWED_AUTHENTICATION_SECRETS = (git_secret )
ENABLED = TRUE;
  
-- CREATE CICD USER, ROLE TO ADD TO GITHUB AND APPLY POLICIES
CREATE USER IF NOT EXISTS GITHUB_ACTIONS_SERVICE_USER
TYPE = SERVICE
COMMENT = 'Service user for GitHub Actions';

-- NOW YOU NEED TO OPEN SNOWSIGHT AND GENERATE THE PAT AND PUT THIS PAT INTO GITHUB ACTIONS 
-- THE PAT SHOULD BE CREATED IN SNOWSIGHT >> GOVERNANCE AND SECURITY >> USERS & ROLES >> CLICK ON THE USER GITHUB_ACTIONS_SERVICE_USER >> PROGRAMMATIC ACCESS TOKENS >> CREATE PAT
-- IN GITHUB ACTIONS SECRETS YOU NEED TO ADD: SNOWFLAKE_ACCOUNT, SNOWFLAKE_PAT, SNOWFLAKE_USER
-- IN GITHUB ACTIONS VARIABLES NEED TO ADD: SNOWFLAKE_DATABASE, SNOWFLAKE_SCHEMA

CREATE SCHEMA IF NOT EXISTS AVIATION_WEATHER_PROJECT.CICD;

CREATE ROLE IF NOT EXISTS GITHUB_ACTIONS_ROLE;
GRANT ROLE GITHUB_ACTIONS_ROLE TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE AVIATION_WEATHER_WAREHOUSE TO ROLE GITHUB_ACTIONS_ROLE;
GRANT USAGE ON DATABASE AVIATION_WEATHER_PROJECT TO ROLE GITHUB_ACTIONS_ROLE;
GRANT CREATE SCHEMA ON DATABASE AVIATION_WEATHER_PROJECT TO ROLE GITHUB_ACTIONS_ROLE;

GRANT USAGE ON SCHEMA AVIATION_WEATHER_PROJECT.RAW_DATA TO ROLE GITHUB_ACTIONS_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA AVIATION_WEATHER_PROJECT.RAW_DATA TO ROLE GITHUB_ACTIONS_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AVIATION_WEATHER_PROJECT.RAW_DATA TO ROLE GITHUB_ACTIONS_ROLE;

GRANT USAGE ON SCHEMA AVIATION_WEATHER_PROJECT.CICD TO ROLE GITHUB_ACTIONS_ROLE;
GRANT CREATE DBT PROJECT ON SCHEMA AVIATION_WEATHER_PROJECT.CICD TO ROLE GITHUB_ACTIONS_ROLE;

GRANT ROLE GITHUB_ACTIONS_ROLE TO USER GITHUB_ACTIONS_SERVICE_USER;
ALTER USER GITHUB_ACTIONS_SERVICE_USER SET DEFAULT_ROLE = GITHUB_ACTIONS_ROLE;
